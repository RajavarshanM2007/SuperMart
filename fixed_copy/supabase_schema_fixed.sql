CREATE OR REPLACE FUNCTION public.fn_login(p_identifier TEXT, p_password TEXT)
RETURNS TABLE (user_id BIGINT, username TEXT, email TEXT, full_name TEXT, phone TEXT, role TEXT)
LANGUAGE sql SECURITY DEFINER SET search_path = public, extensions AS $$
    SELECT u.user_id, u.username, u.email, u.full_name, u.phone, u.role
    FROM   users u
    WHERE  (lower(u.username) = lower(p_identifier) OR lower(u.email) = lower(p_identifier))
      AND  u.password_hash = crypt(p_password, u.password_hash)
      AND  u.role <> 'guest';
$$;
CREATE OR REPLACE FUNCTION public.fn_register_user(
    p_username TEXT, p_email TEXT, p_password TEXT, p_full_name TEXT, p_role TEXT DEFAULT 'customer')
RETURNS TABLE (user_id BIGINT, username TEXT, email TEXT, full_name TEXT, phone TEXT, role TEXT)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions AS $$
BEGIN
    RETURN QUERY
    WITH ins AS (
        INSERT INTO users (username, email, password_hash, full_name, role)
        VALUES (lower(p_username), NULLIF(lower(p_email),''), crypt(p_password, gen_salt('bf', 10)),
                COALESCE(NULLIF(p_full_name,''), p_username), 'customer')   -- FIX: role no longer chosen by caller
        RETURNING users.user_id AS r_id, users.username AS r_un, users.email AS r_em,
                  users.full_name AS r_fn, users.phone AS r_ph, users.role AS r_ro
    )
    SELECT r_id, r_un, r_em, r_fn, r_ph, r_ro FROM ins;
END; $$;
CREATE OR REPLACE FUNCTION public.fn_order_total(p_order_id BIGINT)
RETURNS NUMERIC LANGUAGE sql STABLE AS $$
    SELECT COALESCE(SUM(oi.quantity * oi.unit_price), 0) - COALESCE(MAX(o.discount), 0)
    FROM   orders o LEFT JOIN order_items oi ON oi.order_id = o.order_id
    WHERE  o.order_id = p_order_id;
$$;
CREATE OR REPLACE FUNCTION public.fn_place_order(
    p_user_id BIGINT, p_name TEXT, p_phone TEXT,
    p_line1 TEXT, p_city TEXT, p_state TEXT, p_pincode TEXT,
    p_method TEXT, p_discount_rate NUMERIC, p_items JSONB)
RETURNS TABLE (order_id BIGINT, order_code TEXT, total_amount NUMERIC)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions AS $$
DECLARE
    v_user_id  BIGINT := p_user_id;
    v_addr_id  BIGINT;
    v_order_id BIGINT;
    v_code     TEXT := 'ORD-' || (100000 + floor(random() * 900000))::INT;
    v_subtotal NUMERIC;
    v_discount NUMERIC;
    v_tax      NUMERIC;
    v_ship     NUMERIC;
    v_total    NUMERIC;
    it         JSONB;
BEGIN
    -- FIX: reject empty carts and discount rates that are not active promo codes
    IF p_items IS NULL OR jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
        RAISE EXCEPTION 'Cart is empty';
    END IF;
    IF COALESCE(p_discount_rate, 0) <> 0
       AND NOT EXISTS (SELECT 1 FROM promo_codes WHERE active AND rate = p_discount_rate) THEN
        RAISE EXCEPTION 'Invalid discount rate %', p_discount_rate;
    END IF;
    -- FIX: a supplied user id must belong to an existing non-guest account
    IF v_user_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM users WHERE user_id = v_user_id AND role <> 'guest') THEN
        RAISE EXCEPTION 'Unknown customer %', v_user_id;
    END IF;

    IF v_user_id IS NULL THEN
        INSERT INTO users (username, password_hash, full_name, phone, role)
        VALUES ('guest_' || substr(md5(random()::text), 1, 8),
                crypt(md5(random()::text), gen_salt('bf', 10)), p_name, p_phone, 'guest')
        RETURNING user_id INTO v_user_id;
    ELSE
        UPDATE users SET phone = COALESCE(NULLIF(p_phone,''), phone) WHERE user_id = v_user_id;
    END IF;

    INSERT INTO addresses (user_id, line1, city, state, pincode)
    VALUES (v_user_id, p_line1, p_city, p_state, p_pincode)
    RETURNING address_id INTO v_addr_id;

    INSERT INTO orders (order_code, user_id, address_id) VALUES (v_code, v_user_id, v_addr_id)
    RETURNING orders.order_id INTO v_order_id;
    -- FIX: lock products in a fixed order (prevents deadlocks) and fail on unknown products
    FOR it IN SELECT value FROM jsonb_array_elements(p_items) ORDER BY (value->>'product_id')::BIGINT LOOP
        INSERT INTO order_items (order_id, product_id, quantity, unit_price)
        SELECT v_order_id, p.product_id, (it->>'quantity')::INT, p.price
        FROM   products p WHERE p.product_id = (it->>'product_id')::BIGINT;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Unknown product %', it->>'product_id';
        END IF;
    END LOOP;

    SELECT SUM(oi.quantity * oi.unit_price) INTO v_subtotal FROM order_items oi WHERE oi.order_id = v_order_id;
    v_discount := ROUND(v_subtotal * COALESCE(p_discount_rate, 0), 2);
    v_tax      := ROUND((v_subtotal - v_discount) * 0.05, 2);
    v_ship     := CASE WHEN v_subtotal > 150 THEN 0 ELSE 15 END;
    v_total    := v_subtotal - v_discount + v_tax + v_ship;

    UPDATE orders SET discount = v_discount, total_amount = v_total WHERE orders.order_id = v_order_id;

    INSERT INTO payments (order_id, method, amount, status)
    VALUES (v_order_id, p_method, v_total, CASE WHEN p_method = 'Cash on Delivery' THEN 'Pending' ELSE 'Paid' END);

    RETURN QUERY SELECT v_order_id, v_code, v_total;
END; $$;
CREATE OR REPLACE FUNCTION public.fn_change_password(p_user_id BIGINT, p_old TEXT, p_new TEXT)
RETURNS BOOLEAN LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions AS $$
BEGIN
    UPDATE users SET password_hash = crypt(p_new, gen_salt('bf', 10))
    WHERE  user_id = p_user_id AND password_hash = crypt(p_old, password_hash);
    RETURN FOUND;
END; $$;

