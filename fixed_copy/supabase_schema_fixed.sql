CREATE TABLE public.categories (
    category_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT NOT NULL UNIQUE,
    description  TEXT
);

CREATE TABLE public.users (
    user_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       TEXT NOT NULL UNIQUE,
    email          TEXT UNIQUE,
    password_hash  TEXT NOT NULL,
    full_name      TEXT,
    phone          TEXT,
    role           TEXT NOT NULL DEFAULT 'customer'
                   CHECK (role IN ('customer','manager','guest')),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_username_len CHECK (char_length(username) >= 3)
);

CREATE TABLE public.products (
    product_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         TEXT NOT NULL UNIQUE,
    category_id  BIGINT NOT NULL REFERENCES public.categories(category_id) ON DELETE RESTRICT,
    price        NUMERIC(10,2) NOT NULL CHECK (price > 0),
    stock        INTEGER NOT NULL DEFAULT 10 CHECK (stock >= 0),
    rating       NUMERIC(2,1) NOT NULL DEFAULT 4.5 CHECK (rating BETWEEN 0 AND 5),
    icon         TEXT DEFAULT '📦',
    description  TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.addresses (
    address_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    line1       TEXT NOT NULL,
    city        TEXT NOT NULL,
    state       TEXT NOT NULL,
    pincode     TEXT NOT NULL CHECK (pincode ~ '^[0-9]{5,6}$'),
    is_default  BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE public.orders (
    order_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_code    TEXT NOT NULL UNIQUE,
    user_id       BIGINT NOT NULL REFERENCES public.users(user_id)         ON DELETE RESTRICT,
    address_id    BIGINT NOT NULL REFERENCES public.addresses(address_id)  ON DELETE RESTRICT,
    order_date    TIMESTAMPTZ NOT NULL DEFAULT now(),
    status        TEXT NOT NULL DEFAULT 'Confirmed'
                  CHECK (status IN ('Confirmed','Shipped','Delivered','Cancelled')),
    discount      NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (discount >= 0),
    total_amount  NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0)
);

CREATE TABLE public.order_items (
    order_item_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT NOT NULL REFERENCES public.orders(order_id)     ON DELETE CASCADE,
    product_id     BIGINT NOT NULL REFERENCES public.products(product_id) ON DELETE RESTRICT,
    quantity       INTEGER NOT NULL CHECK (quantity > 0),
    unit_price     NUMERIC(10,2) NOT NULL CHECK (unit_price > 0)
);

CREATE TABLE public.payments (
    payment_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT NOT NULL UNIQUE REFERENCES public.orders(order_id) ON DELETE CASCADE,
    method      TEXT NOT NULL CHECK (method IN ('Credit/Debit Card','UPI','Cash on Delivery')),
    amount      NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    status      TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Paid','Refunded','Cancelled')),
    paid_at     TIMESTAMPTZ
);

CREATE TABLE public.reviews (
    review_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT NOT NULL REFERENCES public.products(product_id) ON DELETE CASCADE,
    user_id      BIGINT NOT NULL REFERENCES public.users(user_id)       ON DELETE CASCADE,
    rating       INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment      TEXT,
    review_date  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_one_review_per_user UNIQUE (product_id, user_id)
);

