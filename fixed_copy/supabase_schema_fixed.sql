CREATE OR REPLACE FUNCTION public.trg_fn_check_stock() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_stock INT; v_name TEXT;
BEGIN
    SELECT stock, name INTO v_stock, v_name FROM products WHERE product_id = NEW.product_id FOR UPDATE;
    IF v_stock < NEW.quantity THEN
        RAISE EXCEPTION 'Insufficient stock for "%" (available %, requested %)', v_name, v_stock, NEW.quantity;
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER trg_check_stock BEFORE INSERT ON public.order_items
FOR EACH ROW EXECUTE FUNCTION public.trg_fn_check_stock();
CREATE OR REPLACE FUNCTION public.trg_fn_reduce_stock() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    UPDATE products SET stock = stock - NEW.quantity WHERE product_id = NEW.product_id;
    RETURN NEW;
END; $$;
CREATE TRIGGER trg_reduce_stock AFTER INSERT ON public.order_items
FOR EACH ROW EXECUTE FUNCTION public.trg_fn_reduce_stock();
CREATE OR REPLACE FUNCTION public.trg_fn_restore_stock() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.status = 'Cancelled' AND OLD.status <> 'Cancelled' THEN
        UPDATE products p SET stock = p.stock + oi.quantity
        FROM   order_items oi
        WHERE  oi.order_id = NEW.order_id AND oi.product_id = p.product_id;
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER trg_restore_stock AFTER UPDATE OF status ON public.orders
FOR EACH ROW EXECUTE FUNCTION public.trg_fn_restore_stock();
CREATE OR REPLACE FUNCTION public.trg_fn_update_rating() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_pid BIGINT := COALESCE(NEW.product_id, OLD.product_id);
BEGIN
    UPDATE products
    SET    rating = COALESCE((SELECT ROUND(AVG(rating)::numeric, 1) FROM reviews WHERE product_id = v_pid), 4.5)
    WHERE  product_id = v_pid;
    RETURN NULL;
END; $$;
CREATE TRIGGER trg_update_rating AFTER INSERT OR UPDATE OR DELETE ON public.reviews
FOR EACH ROW EXECUTE FUNCTION public.trg_fn_update_rating();
CREATE OR REPLACE FUNCTION public.trg_fn_payment_paid_at() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.status = 'Paid' AND NEW.paid_at IS NULL THEN NEW.paid_at := now(); END IF;
    IF NEW.status = 'Pending' THEN NEW.paid_at := NULL; END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER trg_payment_paid_at BEFORE INSERT OR UPDATE ON public.payments
FOR EACH ROW EXECUTE FUNCTION public.trg_fn_payment_paid_at();
