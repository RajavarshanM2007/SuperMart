CREATE OR REPLACE PROCEDURE public.sp_update_order_status(p_order_id BIGINT, p_status TEXT)
LANGUAGE plpgsql AS $$
DECLARE v_old TEXT;
BEGIN
    SELECT status INTO v_old FROM orders WHERE order_id = p_order_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Order % does not exist', p_order_id; END IF;
    -- FIX: only Confirmed -> Shipped/Cancelled and Shipped -> Delivered/Cancelled are allowed
    IF NOT ((v_old = 'Confirmed' AND p_status IN ('Shipped','Cancelled'))
         OR (v_old = 'Shipped'   AND p_status IN ('Delivered','Cancelled'))) THEN
        RAISE EXCEPTION 'Invalid status change % -> %', v_old, p_status;
    END IF;

    UPDATE orders SET status = p_status WHERE order_id = p_order_id;

    IF p_status = 'Delivered' THEN
        UPDATE payments SET status = 'Paid'      WHERE order_id = p_order_id AND status = 'Pending';
    ELSIF p_status = 'Cancelled' THEN
        UPDATE payments SET status = 'Refunded'  WHERE order_id = p_order_id AND status = 'Paid';
        UPDATE payments SET status = 'Cancelled' WHERE order_id = p_order_id AND status = 'Pending';  -- FIX: COD never collected
    END IF;
END; $$;
CREATE OR REPLACE PROCEDURE public.sp_restock_low_stock(p_threshold INT DEFAULT 10, p_add INT DEFAULT 20)
LANGUAGE plpgsql AS $$
DECLARE
    cur_low CURSOR FOR
        SELECT product_id, name, stock FROM products WHERE stock < p_threshold ORDER BY stock;
    rec RECORD;
    v_count INT := 0;
BEGIN
    OPEN cur_low;
    LOOP
        FETCH cur_low INTO rec;
        EXIT WHEN NOT FOUND;
        UPDATE products SET stock = stock + p_add WHERE product_id = rec.product_id;
        RAISE NOTICE 'Restocked % (was %, now %)', rec.name, rec.stock, rec.stock + p_add;
        v_count := v_count + 1;
    END LOOP;
    CLOSE cur_low;
    RAISE NOTICE 'Total products restocked: %', v_count;
END; $$;
CREATE OR REPLACE PROCEDURE public.sp_apply_category_discount(p_category TEXT, p_percent NUMERIC)
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE products p
    SET    price = ROUND(p.price * (1 - p_percent / 100.0), 2)
    FROM   categories c
    WHERE  c.category_id = p.category_id AND c.name = p_category;
END; $$;
CREATE OR REPLACE FUNCTION public.fn_run_restock(p_threshold INT, p_add INT)
RETURNS INT LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, extensions AS $$
DECLARE v_before INT;
BEGIN
    SELECT COUNT(*) INTO v_before FROM products WHERE stock < p_threshold;
    CALL sp_restock_low_stock(p_threshold, p_add);
    RETURN v_before;
END; $$;

